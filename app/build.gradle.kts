    /**
     * Signing is optional: without `keystore.properties` (or the `KEYSTORE_PROPERTIES`
     * environment variable) `assembleRelease` builds unsigned. That file does not belong in the
     * repo, it is listed in `.gitignore`. See the README for its layout.
     */
    val keystoreProps = Properties().apply {
        val f = file(System.getenv("KEYSTORE_PROPERTIES") ?: rootProject.file("keystore.properties").path)
        if (f.exists()) f.inputStream().use { load(it) }
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
                // minSdk 26 needs no v1; v3 keeps a later key rotation possible.
                enableV1Signing = false
                enableV2Signing = true
                enableV3Signing = true
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.findByName("release")
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
